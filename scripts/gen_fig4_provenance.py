"""Generate Figure 4: Provenance Card Example."""

import asyncio
import shutil
from pathlib import Path

from dotenv import load_dotenv

load_dotenv("/home/ubuntu/paperbanana/.env")

from paperbanana import DiagramType, GenerationInput, PaperBananaPipeline
from paperbanana.core.config import Settings


async def main():
    source_context = """
    This is a provenance card diagram for a single feature generated by KnowFeat.
    It shows how domain knowledge flows into feature creation with full traceability.

    The diagram should look like a structured card or flowchart showing:

    FEATURE NAME (top, prominent):
    fan_in_fan_out_ratio

    KNOWLEDGE ASSETS (left column, 4 items connected to the feature):
    - RULE_006: "Scatter-in, gather-out" layering pattern
    - RULE_013: Pyramid-shaped fund networks
    - PAT_A03: Money mule wallet behavior
    - IND_15: Abnormal transaction modes

    REASONING CHAIN (center, numbered steps flowing downward):
    Step 1: From RULE_006 + RULE_013 -> compute fan-in/fan-out ratio
    Step 2: From PAT_A03 -> money mule wallets have fan-in >> fan-out
    Step 3: From IND_15 -> weight by abnormal mode proportion
    Step 4: Combine -> ratio * (1 + abnormal_mode_ratio)

    CODE (bottom right, small code block):
    fi = mode_counts['fan_in'] / n
    fo = mode_counts['fan_out'] / n
    ratio = fi / (fo + eps)
    abnormal = fi + m2m + o2m
    result = ratio * (1 + abnormal)

    VERIFICATION RESULT (bottom, green checkmark):
    L1: PASS | L2: IV=0.34, KS=0.28 | L3: delta-Recall=+0.8pp

    The layout should flow: Knowledge Assets -> Reasoning Chain -> Code -> Verification.
    Use arrows or connecting lines. Academic style, clean, structured like a card.
    Color coding: knowledge assets in light blue boxes, reasoning in white,
    code in light gray box, verification result in light green.
    """

    caption = (
        "Provenance card for the fan_in_fan_out_ratio feature. Each feature records "
        "the knowledge assets, reasoning chain, generated code, and verification results, "
        "enabling full auditability."
    )

    settings = Settings(
        vlm_provider="gemini",
        vlm_model="gemini-2.5-pro",
        image_provider="google_imagen",
        image_model="gemini-3.1-flash-image",
        refinement_iterations=2,
    )

    pipeline = PaperBananaPipeline(settings=settings)

    result = await pipeline.generate(
        GenerationInput(
            source_context=source_context,
            communicative_intent=caption,
            diagram_type=DiagramType.METHODOLOGY,
        )
    )

    out = Path("/home/ubuntu/Projects/大模型提取特征/paper/figures/provenance_card.png")
    shutil.copy(result.image_path, out)
    print(f"Saved to {out}")


if __name__ == "__main__":
    asyncio.run(main())
